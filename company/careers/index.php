<script>
document.addEventListener('DOMContentLoaded', function() {
  // 1. Skill Pill Toggle
  var skillPills = document.querySelectorAll('.skill-pill');
  var selectedSkillsInput = document.getElementById('selected_skills_input');
  var selectedSkills = [];

  skillPills.forEach(function(pill) {
    pill.addEventListener('click', function() {
      var skill = this.getAttribute('data-skill');
      this.classList.toggle('selected');
      if (this.classList.contains('selected')) {
        if (selectedSkills.indexOf(skill) === -1) {
          selectedSkills.push(skill);
        }
      } else {
        var idx = selectedSkills.indexOf(skill);
        if (idx !== -1) {
          selectedSkills.splice(idx, 1);
        }
      }
      selectedSkillsInput.value = selectedSkills.join(', ');
    });
  });

  // 2. Filter Roles Categories
  var filterButtons = document.querySelectorAll('.role-filter-btn');
  var categoryCards = document.querySelectorAll('.role-category-card');
  var rolesGrid = document.querySelector('.roles-grid');

  filterButtons.forEach(function(btn) {
    btn.addEventListener('click', function() {
      filterButtons.forEach(function(b) { b.classList.remove('active'); });
      this.classList.add('active');
      var filter = this.getAttribute('data-filter');
      var visibleCount = 0;

      categoryCards.forEach(function(card) {
        if (filter === 'all' || card.getAttribute('data-cat') === filter) {
          card.style.display = 'flex';
          visibleCount++;
        } else {
          card.style.display = 'none';
        }
      });

      if (rolesGrid) {
        if (filter !== 'all' && visibleCount <= 1) {
          rolesGrid.classList.add('is-single-card');
        } else {
          rolesGrid.classList.remove('is-single-card');
        }
      }
    });
  });

  // 3. One-Click Apply Button Pre-fill
  var applyButtons = document.querySelectorAll('[data-role-select]');
  var roleDropdown = document.getElementById('applicant_role');
  var titleInput = document.getElementById('applicant_title');

  applyButtons.forEach(function(btn) {
    btn.addEventListener('click', function() {
      var roleVal = this.getAttribute('data-role-select');
      var roleTitle = this.getAttribute('data-role-title');

      if (roleDropdown && roleVal) {
        for (var i = 0; i < roleDropdown.options.length; i++) {
          if (roleDropdown.options[i].value === roleVal) {
            roleDropdown.selectedIndex = i;
            break;
          }
        }
      }
      if (titleInput && roleTitle) {
        titleInput.value = roleTitle;
      }
    });
  });

  // 4. Copy Email Handler
  var btnCopyEmail = document.getElementById('btnCopyEmail');
  if (btnCopyEmail) {
    btnCopyEmail.addEventListener('click', function() {
      navigator.clipboard.writeText('careers@hellobotz.com').then(function() {
        btnCopyEmail.textContent = 'Copied to Clipboard! ✓';
        setTimeout(function() {
          btnCopyEmail.textContent = 'Copy Email';
        }, 3000);
      }).catch(function() {
        prompt('Copy our careers email address:', 'careers@hellobotz.com');
      });
    });
  }

  // 5. Careers Form Submission
  var form = document.getElementById('careersApplicationForm');
  var submitBtn = document.getElementById('careersSubmitBtn');
  var statusBox = document.getElementById('careersFormStatus');

  if (form) {
    form.addEventListener('submit', function(e) {
      e.preventDefault();

      // Basic HTML5 validation
      if (!form.checkValidity()) {
        form.reportValidity();
        return;
      }

      var name = document.getElementById('applicant_name').value.trim();
      var email = document.getElementById('applicant_email').value.trim();
      var phone = document.getElementById('applicant_phone').value.trim();
      var location = document.getElementById('applicant_location').value.trim();
      var roleCat = roleDropdown.value;
      var targetTitle = titleInput.value.trim() || roleCat;
      var exp = document.getElementById('applicant_exp').value;
      var empType = document.getElementById('applicant_type').value;
      var skills = selectedSkillsInput.value || 'None specified';
      var portfolio = document.getElementById('applicant_portfolio').value.trim();
      var resume = document.getElementById('applicant_resume').value.trim();
      var about = document.getElementById('applicant_about').value.trim();
      var why = document.getElementById('applicant_why').value.trim();

      submitBtn.disabled = true;
      submitBtn.innerHTML = '<span>Submitting Application...</span>';
      statusBox.style.display = 'none';
      statusBox.className = 'careers-form-status';

      // Comprehensive payload for /api/lead
      var combinedRequirement = [
        "TARGET TITLE: " + targetTitle,
        "LOCATION: " + location,
        "EXPERIENCE: " + exp,
        "EMPLOYMENT TYPE: " + empType,
        "KEY SKILLS: " + skills,
        "PORTFOLIO / GITHUB: " + portfolio,
        "RESUME LINK: " + resume,
        "ABOUT & PROJECTS:\n" + about,
        "WHY HELLOBOTZ:\n" + why
      ].join("\n\n");

      var payload = {
        name: name,
        email: email,
        phone: phone,
        location: location,
        business: location + " (" + exp + ")",
        type: "Job Application: " + targetTitle,
        category: "Careers",
        target_sheet: "Sheet3",
        sheet_name: "Careers",
        role_category: roleCat,
        role: roleCat,
        target_title: targetTitle,
        experience: exp,
        employment_type: empType,
        selected_skills: skills,
        skills: skills,
        portfolio: portfolio,
        resume_link: resume,
        about_projects: about,
        about: about,
        why_hellobotz: why,
        why: why,
        product: roleCat + " | " + skills,
        requirement: combinedRequirement,
        source_page: window.location.href
      };

      fetch('/api/lead', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Accept': 'application/json'
        },
        body: JSON.stringify(payload)
      })
      .then(function(res) {
        return res.json().catch(function() {
          return { ok: res.ok };
        });
      })
      .then(function(data) {
        if (data && data.ok) {
          statusBox.className = 'careers-form-status success';
          statusBox.innerHTML = '<strong>Application Submitted Successfully! 🎉</strong><br>Thank you, ' + escapeHtml(name) + '. Our engineering and recruitment team will review your portfolio and reach out to you via WhatsApp or Email (' + escapeHtml(email) + ') shortly.';
          statusBox.style.display = 'block';
          form.reset();
          selectedSkills = [];
          skillPills.forEach(function(p) { p.classList.remove('selected'); });
          selectedSkillsInput.value = '';
          submitBtn.innerHTML = '<span>Application Sent! ✓</span>';
          setTimeout(function() {
            submitBtn.disabled = false;
            submitBtn.innerHTML = '<span>Submit Another Application</span>';
          }, 5000);
        } else {
          throw new Error(data && data.error ? data.error : 'Submission encountered an error.');
        }
      })
      .catch(function(err) {
        // Mailto fallback link
        var mailSubject = encodeURIComponent("Job Application: " + targetTitle + " - " + name);
        var mailBody = encodeURIComponent(
          "Name: " + name + "\n" +
          "Email: " + email + "\n" +
          "Phone: " + phone + "\n" +
          "Location: " + location + "\n" +
          "Role Category: " + roleCat + "\n" +
          "Target Title: " + targetTitle + "\n" +
          "Experience: " + exp + "\n" +
          "Employment Type: " + empType + "\n" +
          "Skills: " + skills + "\n" +
          "Portfolio: " + portfolio + "\n" +
          "Resume: " + resume + "\n\n" +
          "About & Projects:\n" + about + "\n\n" +
          "Why HelloBotz:\n" + why
        );
        var mailtoUrl = "mailto:careers@hellobotz.com?subject=" + mailSubject + "&body=" + mailBody;

        statusBox.className = 'careers-form-status error';
        statusBox.innerHTML = '<strong>Submission Note:</strong> We had trouble saving automatically. Please <a href="' + mailtoUrl + '" style="font-weight:700;text-decoration:underline;color:#991B1B;">Click here to send directly to careers@hellobotz.com</a>, and your application will be instantly delivered.';
        statusBox.style.display = 'block';
        submitBtn.disabled = false;
        submitBtn.innerHTML = '<span>Retry Submission</span>';
      });
    });
  }

  function escapeHtml(str) {
    return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }
});
